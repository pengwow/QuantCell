#!/usr/bin/env python3
"""从 backend/vocab.py 结构化词条生成前端 TS 类型与词汇表常量（命名审计 P2-5 / F-5）。

单一事实源是 vocab.py 的 VOCAB_ENUMS / VOCAB_DOMAINS；产物
frontend/src/types/vocab.generated.ts 带自动生成头，禁止手改。

用法::

    cd backend && uv run python scripts/export_vocab_types.py
"""

import json
import sys
from pathlib import Path

# 直接执行脚本时 sys.path[0] 是 scripts/，项目包位于 backend/ 下，先补上再导入
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

# 注意：下面的项目包导入必须在 sys.path 注入之后
import vocab

_OUTPUT = Path(__file__).resolve().parent.parent.parent / "frontend" / "src" / "types" / "vocab.generated.ts"


def _ts_type_name(enum_key: str) -> str:
    """side -> Side，position_side -> PositionSide（与生成的 TS 类型名对应）。"""
    return "".join(part.capitalize() for part in enum_key.split("_"))


def main() -> None:
    lines = [
        "/* AUTO-GENERATED by backend/scripts/export_vocab_types.py — DO NOT EDIT.",
        " * 事实源: backend/vocab.py（VOCAB_ENUMS / VOCAB_DOMAINS，命名审计 P2-5）",
        " * 重新生成: cd backend && uv run python scripts/export_vocab_types.py",
        " */",
        "",
        "/** 方向词汇 canonical 值域（铁律1：落库/传输/类型只用 canonical 小写） */",
    ]
    # TS 类型别名（前端字段命名的唯一值域来源）
    for key, values in vocab.VOCAB_ENUMS.items():
        union = " | ".join(f"'{v}'" for v in values)
        lines.append(f"export type {_ts_type_name(key)} = {union};")

    # 词条目录（GET /api/v1/vocab 的同源静态快照；banned 词表供 P2-6 lint 门禁消费）
    payload = {
        "domains": [{"name": d.name, "terms": [t._asdict() for t in d.terms]} for d in vocab.VOCAB_DOMAINS],
        "enums": {k: list(v) for k, v in vocab.VOCAB_ENUMS.items()},
        "banned_terms": sorted(t.term for d in vocab.VOCAB_DOMAINS for t in d.terms if t.kind == "banned"),
    }
    lines += [
        "",
        "/** 禁用词表（canonical 备选词误用检查；lint 门禁消费口） */",
        f"export const BANNED_TERMS = {json.dumps(payload['banned_terms'], ensure_ascii=False)} as const;",
        "",
        "/** 词汇表目录（与 GET /api/v1/vocab 同源） */",
        "export const VOCAB_CATALOG =",
        f"{json.dumps(payload, ensure_ascii=False, indent=2)} as const;",
    ]

    _OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    _OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"written: {_OUTPUT}")


if __name__ == "__main__":
    main()
